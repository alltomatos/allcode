#!/usr/bin/env bun

import { mkdir, readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { SKILLS_COMMIT, SKILLS_REPO } from "./skills-upstream"

const dir = path.resolve(import.meta.dirname, "..")
const skillsDir = path.join(dir, "vendor", "skills")
const manifestPath = path.join(dir, "src", "skill", "skills.gen.ts")
const markerPath = path.join(skillsDir, ".allcode-skills.json")

const MARKER_NAME = ".allcode-skills.json"

async function walk(root: string, prefix = ""): Promise<string[]> {
  const entries = await readdir(prefix ? path.join(root, prefix) : root, { withFileTypes: true })
  const result: string[] = []

  for (const entry of entries) {
    if (!prefix && entry.name === MARKER_NAME) continue
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isDirectory()) result.push(...(await walk(root, relative)))
    if (entry.isFile()) result.push(relative)
  }

  return result
}

async function render() {
  const paths = (await walk(skillsDir)).toSorted()
  const files = await Promise.all(
    paths.map(async (relative) => [relative, await readFile(path.join(skillsDir, relative), "utf8")] as const),
  )

  const manifest = [
    "// Generated by script/generate-skills.ts. Do not edit by hand.",
    `// Source: ${SKILLS_REPO}@${SKILLS_COMMIT}`,
    `export const VERSION = ${JSON.stringify(SKILLS_COMMIT)}`,
    "",
    "export const FILES: Record<string, string> = {",
    ...files.map(([relative, content]) => `  ${JSON.stringify(relative)}: ${JSON.stringify(content)},`),
    "}",
    "",
  ].join("\n")

  const marker = `${JSON.stringify(
    { version: SKILLS_COMMIT, repository: SKILLS_REPO, files: files.length },
    null,
    2,
  )}\n`

  return { manifest, marker, count: files.length }
}

export async function generate() {
  const { manifest, marker, count } = await render()
  await mkdir(path.dirname(manifestPath), { recursive: true })
  await writeFile(manifestPath, manifest)
  await writeFile(markerPath, marker)
  return { count, manifestPath, markerPath }
}

export async function check() {
  const { manifest, marker } = await render()
  const currentManifest = await readFile(manifestPath, "utf8").catch(() => "")
  const currentMarker = await readFile(markerPath, "utf8").catch(() => "")

  const normalize = (s: string) => s.replace(/\r\n/g, "\n").trim()

  if (normalize(currentManifest) !== normalize(manifest)) {
    throw new Error(
      `Generated skills manifest is stale. Run "bun run script/generate-skills.ts" from packages/allcode.`,
    )
  }
  if (normalize(currentMarker) !== normalize(marker)) {
    throw new Error(
      `Vendored skills marker is stale. Run "bun run script/generate-skills.ts" from packages/allcode.`,
    )
  }
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    await check()
    console.log("Vendored skills manifest is up to date")
  } else {
    const result = await generate()
    console.log(`Generated ${result.count} skill files into ${result.manifestPath}`)
  }
}
